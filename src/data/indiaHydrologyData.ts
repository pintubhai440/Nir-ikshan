/**
 * India National Hydrological Telemetry Grid Dataset
 * Synced with India-WRIS (Water Resources Information System) & ISRO Bhuvan WBIS
 * 
 * Categories:
 * 1. Reservoirs & Dams (CWC & State Irrigation) - 💧
 * 2. River Water Level Gauges (CWC) - 🌊
 * 3. River Water Discharge Gauges (CWC) - 🌊
 * 4. Rainfall Telemetry (IMD AWS & State Networks) - 🌧️
 * 5. Ground Water Level (CGWB DWLR Telemetry & Piezometers) - ⛏️
 * 6. ISRO Bhuvan WBIS Satellite Water Bodies & NDWI (Including Sookh Kar Mit Gaye Extinct Beds) - 🛰️
 */

export type TelemetryCategory = 
  | 'reservoir' 
  | 'river_level' 
  | 'river_discharge' 
  | 'rainfall' 
  | 'groundwater' 
  | 'bhuvan_wbis';

export type WaterHealthStatus = 
  | 'green'   // Pristine / High Storage / Recharge Abundant
  | 'blue'    // Normal Govt Telemetry Flow / Stable
  | 'yellow'  // Warning Level / Moderate Silt / Depleting
  | 'red'     // Danger Mark / Severe Hazard / Flood / Contamination
  | 'grey';   // Sookh Kar Mit Gaya / Extinct Bed / Encroached

export interface SatelliteOpticalPass {
  passNumber: number;
  passDate: string;
  ndwiScore: number;
  classification: string;
}

