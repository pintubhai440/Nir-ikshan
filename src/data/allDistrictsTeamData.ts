// Complete helper to get workers for ANY of the 26 districts (at least 5)
export function getWorkersForDistrict(districtName: string): SupabaseActionWorkerRow[] {
  if (!districtName) return COMPLETE_AP_ACTION_WORKERS.slice(0, 5);
  const dLower = districtName.toLowerCase().replace(/district/g, '').trim();

  const direct = COMPLETE_AP_ACTION_WORKERS.filter(w => {
    const rowD = w.district.toLowerCase().replace(/district/g, '').trim();
    return rowD === dLower || rowD.includes(dLower) || dLower.includes(rowD);
  });

  if (direct.length >= 5) return direct;

  const shortCode = districtName.slice(0, 3).toUpperCase();
  const base = [...direct];

  const templates: Array<{ title: string; type: SupabaseActionWorkerRow['type']; skill: string }> = [
    { title: `${districtName} Heavy Desilting Unit #1`, type: 'Crew', skill: 'heavy excavator, waste cleaning/desilting' },
    { title: `Er. M. Srinivasa Rao (${districtName})`, type: 'Engineer', skill: 'structural repair/reinforcing, spillway masonry' },
    { title: `${districtName} Earthworks Contractors`, type: 'Contractor', skill: 'desilting,bund repair,stone pitching' },
    { title: `${districtName} Rapid Remediation Squad`, type: 'Crew', skill: 'waste cleaning,plastic removal,weed dredging' },
    { title: `K. Appala Raju (${districtName})`, type: 'Individual', skill: 'plumbing/structural repair, valve greasing' },
  ];

  for (let i = base.length; i < 5; i++) {
    const tmpl = templates[i % templates.length];
    base.push({
      worker_id: `MW-${shortCode}-${String(i + 1).padStart(2, '0')}`,
      name_or_crew_type: tmpl.title,
      type: tmpl.type,
      contact_person: tmpl.type === 'Individual' || tmpl.type === 'Engineer' ? tmpl.title.split(' ')[0] : 'Squad Lead',
      phone: `+91 94905 ${Math.floor(10000 + i * 1111)}`,
      skills: tmpl.skill,
      service_areas: `${districtName} Command Area`,
      district: districtName,
      nodal_officer_id: `NO-${shortCode}-01`,
      availability: i === 2 ? 'Busy' : 'Available',
      languages: 'Telugu',
      status: 'Active',
      open_tasks: i === 2 ? 3 : i === 0 ? 2 : 1,
      tasks_declined: 0,
      no_response: 0,
      added_on: '2025-11-20',
    });
  }

  return base;
}

/**
 * Converts Supabase rows into standard TeamMemberProfile objects for a district
 */
export function getUnifiedDistrictTeam(districtName: string): TeamMemberProfile[] {
  const inspectors = getInspectorsForDistrict(districtName);
  const workers = getWorkersForDistrict(districtName);

  const team: TeamMemberProfile[] = [];

  for (const i of inspectors) {
    team.push({
      id: `sup-insp-${i.inspector_id.toLowerCase()}`,
      employeeCode: i.inspector_id,
      name: i.full_name,
      role: 'Field Inspector',
      designation: `Field Inspector ${i.meter_id ? `(Meter ${i.meter_id})` : ''}`,
      specialization: i.meter_id 
        ? `Calibrated Digital Meter (${i.meter_id}) • Water Quality & Silt Auditing` 
        : 'TDS Multi-Parameter Water Testing',
      phone: i.phone,
      maskedPhone: `${i.phone.slice(0, 7)}******${i.phone.slice(-2)}`,
      assignedMandals: [i.mandal],
      activeTasks: i.open_inspections,
      capacityLimit: 10,
      overdueTasks: i.overdue_inspections,
      status: i.status === 'Inactive' ? 'Inactive' : i.status === 'On leave' ? 'Standby' : i.overdue_inspections > 0 ? 'Overloaded' : 'Optimal',
      rating: 4.9,
      meterId: i.meter_id,
      meterCalibrated: i.meter_last_calibrated,
      languages: i.languages,
      email: i.email,
      district: i.district,
      joinedOn: i.joined_on,
    });
  }

  for (const w of workers) {
    const areas = w.service_areas.split(/[\/,;]/).map(s => s.trim()).filter(Boolean);
    const workerName = w.name_or_crew || w.name_or_crew_type || 'Action Worker Unit';
    team.push({
      id: `sup-wrk-${w.worker_id.toLowerCase()}`,
      employeeCode: w.worker_id,
      name: workerName,
      role: 'Action Worker',
      designation: `${w.type} (Lead: ${w.contact_person})`,
      specialization: `${w.skills} • Areas: ${w.service_areas}`,
      phone: w.phone,
      maskedPhone: `${w.phone.slice(0, 7)}******${w.phone.slice(-2)}`,
      assignedMandals: areas.length > 0 ? areas : [w.district],
      activeTasks: w.open_tasks,
      capacityLimit: 8,
      overdueTasks: 0,
      status: w.status === 'Inactive' ? 'Inactive' : w.availability === 'Busy' ? 'On Duty' : w.availability === 'On leave' ? 'Standby' : 'Available',
      rating: 4.9,
      workerType: w.type,
      contactPerson: w.contact_person,
      skills: w.skills,
      languages: w.languages,
      district: w.district,
      joinedOn: w.added_on,
    });
  }

  return team;
}

